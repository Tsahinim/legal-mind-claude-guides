    page.insert_htmlbox(fitz.Rect(52, 46, 543, 796), html + DISC,
                        css=CSS, archive=fitz.Archive(FONTDIR))
    pix = page.get_pixmap(dpi=190)
    img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("L")
    img = img.rotate(random.uniform(-0.55, 0.55), resample=Image.BICUBIC,
                     fillcolor=248, expand=False)
    img = img.filter(ImageFilter.GaussianBlur(0.35))
    img = ImageEnhance.Contrast(img).enhance(random.uniform(0.9, 1.05))
    doc.close()
    buf = io.BytesIO(); img.convert("RGB").save(buf, "JPEG", quality=72)
    out = fitz.open()
    p2 = out.new_page(width=595, height=842)
    p2.insert_image(fitz.Rect(0, 0, 595, 842), stream=buf.getvalue())
    fn = bad_name(i)
    out.save(os.path.join(OUT, fn)); out.close()
    key.append({"קובץ": fn, "סוג": kind, "תאריך": date})

