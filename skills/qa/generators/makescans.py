# שמות גרועים בכוונה
def bad_name(i):
    r = i % 5
    if r == 0: return "scan_%04d.pdf" % (30 + i * 7)
    if r == 1: return "מסמך חדש (%d).pdf" % (i // 5 + 1)
    if r == 2: return "IMG_2025%03d.pdf" % (100 + i)
    if r == 3: return "doc%d_final_v2.pdf" % (i + 1)
    return "%d-%02d-%02d_0001.pdf" % (2025, random.randint(1, 8), random.randint(1, 28))

