def build_pdf(html, path, scanned=False):
    """יוצר PDF. scanned=True מפיק קובץ תמונה בלבד, בלי טקסט חיפוש."""
    arch = fitz.Archive(FONTDIR)
    mediabox = fitz.paper_rect("a4")
    where = mediabox + (56, 56, -56, -56)

    tmp = path if not scanned else path + ".tmp"
    writer = fitz.DocumentWriter(tmp)
    story = fitz.Story(html=html, user_css=CSS, archive=arch)
    more = 1
    while more:
        dev = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()

    if not scanned:
        return path

    doc = fitz.open(tmp)

    # הדמיית סריקה: רסטור של כל עמוד, הטיה קלה ורעש, ואז PDF מתמונות בלבד
    from PIL import Image, ImageFilter
    scan = fitz.open()
    random.seed(7)
    for i, page in enumerate(doc):
        pix = page.get_pixmap(dpi=200, colorspace=fitz.csGRAY)
        img = Image.frombytes("L", (pix.width, pix.height), pix.samples)
        img = img.rotate(random.uniform(-0.5, 0.5), resample=Image.BICUBIC,
                         fillcolor=246, expand=False)
        img = img.point(lambda p: min(255, int(p * 0.96) + 9))     # דהייה
        img = img.filter(ImageFilter.GaussianBlur(0.35))            # ריכוך
        buf = io.BytesIO(); img.save(buf, format="JPEG", quality=72)
        p2 = scan.new_page(width=595, height=842)
        p2.insert_image(fitz.Rect(0, 0, 595, 842), stream=buf.getvalue())
    scan.save(path, deflate=True)
    scan.close(); doc.close()
    try:
        os.remove(tmp)
    except OSError:
        pass
    return path


