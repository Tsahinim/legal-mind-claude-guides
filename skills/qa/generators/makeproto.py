class Pool:
    def __init__(s, items): s.items, s.recent = items, []
    def take(s):
        cap = max(1, min(8, len(s.items) - 2))
        for _ in range(60):
            x = random.choice(s.items)
            if x not in s.recent:
                s.recent.append(x)
                while len(s.recent) > cap: s.recent.pop(0)
                return x
        return random.choice(s.items)

